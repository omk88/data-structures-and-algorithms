# A subarray / substring is different from a subsequence.

# A subarray / substring must be **contiguous**. The elements must be right next to eachother in the original array without any gaps.
# A subsequence does **not** need to be contiguous. You can skip elements, pick numbers from the very beginning, the very middle and the very end, as long as you keep their relative order.

# If a problem allows you to pick any two elements and the order doesn't matter, always consider sorting. Sorting often unlocks the ability to use Two Pointers or Sliding Windows on non-contiguous data.